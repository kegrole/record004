ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FIXTURES = os.path.join(ROOT, "fixtures")


def read_file(path):
    with open(path, "rb") as handle:
        return handle.read()


class TestCriterion1SPS(unittest.TestCase):
    def test_sps_construction_and_dimensions(self):
        sps = build_sps(
            profile_idc=100,
            constraint_set=0,
            level_idc=40,
            log2_max_frame_num_minus4=0,
            pic_order_cnt_type=2,
            max_num_ref_frames=1,
            gaps_in_frame_num_value_allowed_flag=0,
            pic_width_in_mbs_minus1=79,
            pic_height_in_map_units_minus1=44,
            frame_mbs_only_flag=1,
            direct_8x8_inference_flag=1,
            vui_parameters_present_flag=0,
        )
        self.assertEqual(sps[0] & 0x1F, 7)
        info = parse_sps(sps)
        self.assertEqual(info["width"], 1280)
        self.assertEqual(info["height"], 720)
        self.assertEqual(info["profile_idc"], 100)
        self.assertEqual(info["constraint_set"], 0)
        self.assertEqual(info["level_idc"], 40)
        self.assertEqual(info["sps_id"], 0)
        self.assertEqual(info["log2_max_frame_num_minus4"], 0)
        self.assertEqual(info["pic_order_cnt_type"], 2)
        self.assertEqual(info["max_num_ref_frames"], 1)
        self.assertEqual(info["gaps_in_frame_num_value_allowed_flag"], 0)
        self.assertEqual(info["frame_mbs_only_flag"], 1)
        self.assertEqual(info["direct_8x8_inference_flag"], 1)
        self.assertEqual(info["vui_parameters_present_flag"], 0)

        fixture_info = parse_sps(read_file(os.path.join(FIXTURES, "sps.h264")))
        self.assertEqual((fixture_info["width"], fixture_info["height"]), (1280, 720))


class TestCriterion2EmulationPrevention(unittest.TestCase):
    def test_natural_and_forced_escapes(self):
        sps = build_sps()

        forced = read_file(os.path.join(FIXTURES, "sps_forced_escapes.h264"))
        self.assertGreaterEqual(forced.count(b"\x00\x00\x03"), 2)
        info = parse_sps(forced)
        self.assertEqual((info["width"], info["height"]), (1280, 720))

        # A genuine 0x03 without a preceding 00 00 must never be deleted.
        genuine = b"\x01\x03\x00\x03\x03"
        self.assertEqual(remove_emulation_prevention(genuine), genuine)

        # 00 00 03 followed by 00/01 is an escape: only the 03 disappears.
        self.assertEqual(
            remove_emulation_prevention(b"\x00\x00\x03\x00\x00\x00\x03\x01"),
            b"\x00\x00\x00\x00\x00\x01",
        )

        sample = sps + b"\xAB\x03\xCD"
        self.assertEqual(remove_emulation_prevention(sample), sample)


class TestCriterion3AnnexB(unittest.TestCase):
    def test_mixed_start_codes(self):
        stream = read_file(os.path.join(FIXTURES, "annexb_mixed.h264"))
        nals = split_annexb(stream)
        self.assertEqual([nal.type for nal in nals], [7, 8, 5, 1])

    def test_split_and_avcc_roundtrip(self):
        sps = build_sps()
        pps = build_pps()
        idr = bytes([0x65, 0x88, 0x80])
        non_idr = bytes([0x41, 0x9A])
        stream = (
            b"\x00\x00\x01" + sps
            + b"\x00\x00\x00\x01" + pps
            + b"\x00\x00\x01" + idr
            + b"\x00\x00\x00\x01" + non_idr
        )
        nals = split_annexb(stream)
        self.assertEqual([nal.type for nal in nals], [7, 8, 5, 1])
        self.assertEqual(nals[2].payload, idr)
        self.assertEqual(nals[3].payload, non_idr)

        avcc, parsed = annexb_to_avcc(stream)
        cursor = 0
        for nal in parsed:
            length = int.from_bytes(avcc[cursor:cursor + 4], "big")
            self.assertEqual(length, len(nal.payload))
            self.assertEqual(avcc[cursor + 4:cursor + 4 + length], nal.payload)
            cursor += 4 + length
        self.assertEqual(cursor, len(avcc))
        self.assertNotIn(b"\x00\x00\x01", avcc)


class TestCriterion4BoxShapes(unittest.TestCase):
    WIDTH = 160
    HEIGHT = 96
    FRAME_COUNT = 4

    def setUp(self):
        self.sps, self.pps, self.frames = build_demo_frames(
            self.FRAME_COUNT, self.WIDTH, self.HEIGHT
        )

    def _check_shape(self, path, data, expected_offset_type, force_largesize):
        info = read_mp4(data)
        self.assertEqual(info.sample_count, self.FRAME_COUNT)
        self.assertEqual(info.width, self.WIDTH)
        self.assertEqual(info.height, self.HEIGHT)
        self.assertEqual(info.offset_box_type, expected_offset_type)
        self.assertEqual(
            [frame.duration for frame in info.frames],
            [FRAME_DURATION] * self.FRAME_COUNT,
        )
        self.assertEqual(info.duration, self.FRAME_COUNT * FRAME_DURATION)
        self.assertEqual(
            info.mvhd_duration,
            info.duration * info.mvhd_timescale // info.timescale,
        )

        def walk(boxes):
            for box in boxes:
                header = data[
                    box.payload_offset - box.header_size:box.payload_offset
                ]
                self.assertEqual(header[4:8], box.type.encode("latin-1"))
                if box.header_size == 16:
                    self.assertEqual(int.from_bytes(header[:4], "big"), 1)
                    self.assertEqual(
                        int.from_bytes(header[8:16], "big"), box.size
                    )
                walk(box.children)

        walk(parse_boxes(data))

        if force_largesize:
            mdat = find_box(parse_boxes(data), "mdat")
            self.assertEqual(mdat.header_size, 16)
            with open(path, "rb") as handle:
                handle.seek(mdat.payload_offset - 16)
                raw = handle.read(16)
            self.assertEqual(int.from_bytes(raw[:4], "big"), 1)
            self.assertEqual(raw[4:8], b"mdat")
            self.assertEqual(int.from_bytes(raw[8:16], "big"), mdat.size)

    def _write(self, data, name):
        path = os.path.join(self.tempdir, name)
        with open(path, "wb") as handle:
            handle.write(data)
        return path

    def test_all_three_shapes_and_fixtures(self):
        with tempfile.TemporaryDirectory() as self.tempdir:
            plain = mux_mp4(self.frames, self.WIDTH, self.HEIGHT, self.sps, self.pps)
            self._check_shape(
                self._write(plain.data, "plain.mp4"), plain.data, "stco", False
            )

            large = mux_mp4(
                self.frames, self.WIDTH, self.HEIGHT, self.sps, self.pps,
                force_largesize=True,
            )
            self._check_shape(
                self._write(large.data, "large.mp4"), large.data, "stco", True
            )

            co64 = mux_mp4(
                self.frames, self.WIDTH, self.HEIGHT, self.sps, self.pps,
                use_co64=True,
            )
            self._check_shape(
                self._write(co64.data, "co64.mp4"), co64.data, "co64", False
            )

            for name, offset_type, largesize in (
                ("plain.mp4", "stco", False),
                ("largesize.mp4", "stco", True),
                ("co64.mp4", "co64", False),
            ):
                data = read_file(os.path.join(FIXTURES, name))
                self._check_shape(
                    os.path.join(FIXTURES, name), data, offset_type, largesize
                )


class TestCriterion5ByteOffsets(unittest.TestCase):
    def _verify_prefixes_on_disk(self, data, expected_frames, use_co64):
        result = mux_mp4(data, 160, 96, self.sps, self.pps, use_co64=use_co64)
        with tempfile.TemporaryDirectory() as directory:
            path = os.path.join(directory, "offset.mp4")
            with open(path, "wb") as handle:
                handle.write(result.data)
            info = read_mp4(result.data)
            with open(path, "rb") as handle:
                for frame, original in zip(info.frames, expected_frames):
                    handle.seek(frame.offset)
                    prefix = handle.read(4)
                    length = int.from_bytes(prefix, "big")
                    self.assertEqual(length, frame.size - 4)
                    self.assertEqual(prefix + handle.read(length), original)

    def setUp(self):
        self.sps, self.pps, frames = build_demo_frames(3, 160, 96)
        self.frames = frames

    def test_stco_offsets_point_at_avcc_prefix(self):
        self._verify_prefixes_on_disk(self.frames, self.frames, False)

    def test_co64_offsets_point_at_avcc_prefix(self):
        self._verify_prefixes_on_disk(self.frames, self.frames, True)


class TestCriterion6SelfContained(unittest.TestCase):
    def test_muxer_parser_consistency(self):
        frame_count = 6
        sps, pps, frames = build_demo_frames(frame_count, 160, 96)
        result = mux_mp4(frames, 160, 96, sps, pps)
        data = result.data
        info = read_mp4(data)

        self.assertEqual(info.sample_count, frame_count)
        self.assertEqual(sum(info.sample_sizes), result.mdat_payload_length)
        self.assertEqual(info.chunk_offsets[0], result.mdat_payload_offset)
        mdat = find_box(parse_boxes(data), "mdat")
        self.assertEqual(result.mdat_payload_offset, mdat.payload_offset)

        self.assertEqual(info.duration, frame_count * FRAME_DURATION)
        self.assertEqual(
            info.mvhd_duration * info.timescale,
            info.duration * info.mvhd_timescale,
        )
        self.assertEqual(info.duration / info.timescale, frame_count / 30)
        self.assertEqual(sum(frame.duration for frame in info.frames), info.duration)

        boxes = parse_boxes(data)
        self.assertEqual(sum(box.size for box in boxes), len(data))

    def test_keyframe_table(self):
        sps, pps, frames = build_demo_frames(4, 160, 96)
        keyframes = [1, 3]
        result = mux_mp4(frames, 160, 96, sps, pps, keyframe_numbers=keyframes)
        info = read_mp4(result.data)
        self.assertEqual(info.keyframe_numbers, keyframes)
        self.assertEqual(
            [frame.is_keyframe for frame in info.frames],
            [True, False, True, False],
        )


class TestDemoEntryPoint(unittest.TestCase):
    def test_demo_command(self):
        with tempfile.TemporaryDirectory() as directory:
            out = os.path.join(directory, "nested", "demo.mp4")
            proc = subprocess.run(
                [sys.executable, "-m", "mp4.muxer", "--demo", "--out", out],
                cwd=ROOT,
                capture_output=True,
                text=True,
                timeout=90,
            )
            self.assertEqual(proc.returncode, 0, proc.stderr)
            self.assertIn("frames=", proc.stdout)
            self.assertIn("boxes=[", proc.stdout)
            data = read_file(out)
            info = read_mp4(data)
            self.assertEqual(info.sample_count, 5)
            self.assertEqual((info.width, info.height), (160, 96))


